import { hashJson, type JsonValue } from './canonical';
import type { Fact, Facts } from './facts';
import type { Bundle } from './schema';
import { decodeBundle, decodeConsent, hashCartBody, hashCartWarrant, parseBundle } from './warrant';

/**
 * Deterministic evidence packet for a dispute (docs/dispute-resolution.md section 5): the consented cart, the
 * signature results, registry and transparency-log status, payer binding, tracking and the listing snapshot,
 * assembled only from the facts and the stored bundle. Same inputs, byte-identical output: the packet holds no
 * timestamps of its own and nothing generated by a model. The caller renders it (PDF or image) and a model may
 * write a summary from it, but every claim must trace to a value in this JSON.
 */

export const EVIDENCE_PACKET_VERSION = '0.1';

export type EvidencePacket = { readonly [key: string]: JsonValue };

function factSummary(fact: Fact<boolean | number | null>): JsonValue {
  return {
    name: fact.name,
    value: fact.value,
    evidence: [...fact.evidence],
    ...(fact.detail === undefined ? {} : { detail: { ...fact.detail } }),
  };
}

/** Build the packet. `bundle` is the stored warrant bundle (object or JSON string), or null when none exists. */
export function buildEvidencePacket(facts: Facts, bundle: unknown): EvidencePacket {
  const parsed = bundle === null || bundle === undefined ? null : parseBundle(bundle);
  const stored: Bundle | null = parsed !== null && parsed.ok ? parsed.value : null;
  const decoded = stored === null ? null : decodeBundle(stored);
  const mandate = decoded !== null && decoded.mandate.ok ? decoded.mandate : null;
  const cart = decoded !== null && decoded.cart.ok ? decoded.cart : null;
  const ctx = facts.context;

  const warrant: JsonValue =
    stored === null || mandate === null || cart === null
      ? null
      : {
          version: stored.warrant_version,
          bundle: { mandate: stored.mandate, cart: stored.cart },
          mandate_jti: mandate.payload.jti,
          mandate_hash: mandate.hash,
          cart_jti: cart.payload.jti,
          cart_hash: cart.payload.cart_hash,
          presented_cart_hash: hashCartBody(cart.payload.cart),
          cart_warrant_hash: hashCartWarrant(cart.payload),
          verification_path: `/v/${cart.payload.jti}`,
        };

  // What the consent signature says it covers. Read without checking the signature: signatures_valid in the packet says whether it holds.
  const signedConsent = cart === null || cart.payload.consent.signature === undefined ? null : decodeConsent(cart.payload.consent.signature);
  const consentCovers: JsonValue =
    signedConsent === null || !signedConsent.ok
      ? null
      : { cart_hash: signedConsent.payload.cart_hash, cart_jti: signedConsent.payload.cart_jti, aud: signedConsent.payload.aud, mandate_hash: signedConsent.payload.mandate_hash };

  const consentedCart: JsonValue =
    cart === null
      ? null
      : {
          currency: cart.payload.cart.currency,
          items: cart.payload.cart.items.map((i) => ({ sku: i.sku, title: i.title, qty: i.qty, unit_price: i.unit_price, listing_hash: i.listing_hash })),
          total: cart.payload.cart.total,
          consent: {
            mode: cart.payload.consent.mode,
            approved_at: cart.payload.consent.approved_at ?? null,
            method: cart.payload.consent.method ?? null,
            presented_hash: cart.payload.consent.presented_hash ?? null,
            covers: consentCovers,
          },
        };

  const mandateScope: JsonValue =
    mandate === null
      ? null
      : {
          instruction: mandate.payload.instruction.text,
          issuer: mandate.payload.iss,
          not_before: mandate.payload.nbf,
          expires: mandate.payload.exp,
          agent: { platform: mandate.payload.agent.platform, agent_id: mandate.payload.agent.agent_id, kid: mandate.payload.agent.kid },
          scope: {
            currency: mandate.payload.scope.currency,
            max_total: mandate.payload.scope.max_total,
            max_per_item: mandate.payload.scope.max_per_item,
            max_items: mandate.payload.scope.max_items,
            categories_allow: mandate.payload.scope.categories_allow === null ? null : [...mandate.payload.scope.categories_allow],
            merchants_allow: [...mandate.payload.scope.merchants_allow],
            merchants_deny: [...mandate.payload.scope.merchants_deny],
            mode: mandate.payload.scope.mode,
            budget_mode: mandate.payload.scope.budget_mode,
          },
        };

  const packet: { [key: string]: JsonValue } = {
    packet_version: EVIDENCE_PACKET_VERSION,
    dispute_id: ctx.disputeId,
    capture_id: ctx.captureId,
    order_id: ctx.orderId,
    warrant,
    consented_cart: consentedCart,
    mandate: mandateScope,
    signatures: {
      all_valid: facts.F2.value,
      agent: facts.F2.detail?.['cart'] ?? null,
      wallet: facts.F2.detail?.['mandate'] ?? null,
      consent: facts.F2.detail?.['consent'] ?? null,
      evidence: [...facts.F2.evidence],
    },
    registry: { keys_active_at_issue: facts.F3.value, evidence: [...facts.F3.evidence] },
    transparency_log:
      ctx.transparency === null
        ? null
        : { included: ctx.transparency.included, seq: ctx.transparency.seq, entry_hash: ctx.transparency.entryHash, logged_at: ctx.transparency.loggedAt },
    payer_binding: { bound: facts.F7.value, evidence: [...facts.F7.evidence] },
    order_matches_consent: { value: facts.F5.value, evidence: [...facts.F5.evidence], ...(facts.F5.detail === undefined ? {} : { detail: { ...facts.F5.detail } }) },
    tracking: { delivered: facts.F9.value, evidence: [...facts.F9.evidence], ...(facts.F9.detail === undefined ? {} : { detail: { ...facts.F9.detail } }) },
    listing_snapshot: ctx.listings.map((l) => ({ sku: l.sku, warrant_listing_hash: l.warrantListingHash, fulfilled_listing_hash: l.fulfilledListingHash })),
    merchant_mode: ctx.merchantMode,
    facts: {
      F1: factSummary(facts.F1),
      F2: factSummary(facts.F2),
      F3: factSummary(facts.F3),
      F4: factSummary(facts.F4),
      F5: factSummary(facts.F5),
      F6: factSummary(facts.F6),
      F7: factSummary(facts.F7),
      F8: factSummary(facts.F8),
      F9: factSummary(facts.F9),
      F10: factSummary(facts.F10),
      F11: factSummary(facts.F11),
      F12: factSummary(facts.F12),
      F13: factSummary(facts.F13),
    },
  };

  return { ...packet, packet_hash: hashJson(packet) };
}
